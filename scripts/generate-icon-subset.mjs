import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
// Google Material Symbols registry, Apache-2.0. See scripts/data/README.md.
const known = new Set(fs.readFileSync(path.join(root, 'scripts/data/material-symbols.codepoints'), 'utf8')
  .split('\n').map(line => line.split(' ')[0]));
const names = new Set();
function walk(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) walk(filename);
    else if (/\.[cm]?tsx?$/.test(filename) && entry.name !== 'material-symbols.ts') {
      const source = ts.createSourceFile(filename, fs.readFileSync(filename, 'utf8'), ts.ScriptTarget.Latest, true);
      function visit(node) {
        // Includes icons in conditional expressions, configuration objects and props.
        if (ts.isStringLiteralLike(node) || ts.isJsxText(node)) {
          const value = node.text.trim();
          if (value && known.has(value)) names.add(value);
        }
        ts.forEachChild(node, visit);
      }
      visit(source);
    }
  }
}
walk(path.join(root, 'src'));
const output = `// Generated by scripts/generate-icon-subset.mjs; do not edit.\nexport const materialSymbolNames = ${JSON.stringify([...names].sort().join(','))};\n`;
const target = path.join(root, 'src/lib/material-symbols.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) fs.writeFileSync(target, output);
console.log(`Material Symbols: ${names.size} icons included.`);
