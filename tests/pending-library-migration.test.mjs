import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const modulePath = process.env.PGLITE_MODULE;
test('migration: transactional queue, coalescing, tombstones, isolation and imports', {skip:!modulePath}, async()=>{
 const {PGlite}=require(modulePath);
 const db=new PGlite();
 const uid='00000000-0000-0000-0000-000000000001';
 const other='00000000-0000-0000-0000-000000000002';
 const mid='00000000-0000-0000-0000-000000000010';
 try {
 await db.exec(`create role anon; create role authenticated; create role service_role;
 create schema auth;
 create function auth.uid() returns uuid language sql as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 create function auth.role() returns text language sql as $$select current_setting('request.jwt.claim.role',true)$$;
 create table auth.users(id uuid primary key);
 create table public.media(id uuid primary key,mal_id bigint,type text);
 create table public.favorites(user_id uuid,media_id uuid);
 create table public.user_media_progress(user_id uuid,media_id uuid,status text,current_episode integer);
 create table public.hentai(user_id uuid,mal_id bigint,type text);
 create table public.anilist_connections(user_id uuid,anilist_user_id bigint);
 create table public.mal_connections(user_id uuid,mal_user_id bigint);
 insert into auth.users values ('${uid}'),('${other}');
 insert into media values ('${mid}',10,'anime');
 insert into anilist_connections values ('${uid}',100);
 insert into mal_connections values ('${uid}',200);
 grant usage on schema public,auth to authenticated;
 grant all on public.favorites,public.user_media_progress,public.hentai to authenticated;
 set request.jwt.claim.sub='${uid}';set request.jwt.claim.role='authenticated';`);
 await db.exec(fs.readFileSync('supabase/migrations/202610280001_library_sync_pending.sql','utf8'));
 await db.exec(`set role authenticated; insert into favorites values ('${uid}','${mid}');insert into user_media_progress values ('${uid}','${mid}','plan_to_watch',0);`);
 let rows=(await db.query('select * from library_sync_pending order by provider')).rows;
 assert.equal(rows.length,2);assert.equal(rows[0].favorite_only,true);
 const revision=rows[0].revision;
 await db.exec(`update user_media_progress set status='watching',current_episode=3;update user_media_progress set current_episode=5;`);
 rows=(await db.query('select * from library_sync_pending order by provider')).rows;
 assert.equal(rows.length,2);assert.equal(rows[0].progress,5);assert.equal(rows[0].favorite_only,false);assert.notEqual(rows[0].revision,revision);
 await db.exec('begin; update user_media_progress set current_episode=9; rollback;');
 assert.equal((await db.query('select progress from library_sync_pending')).rows[0].progress,5);
 await db.exec('delete from favorites;');
 assert.equal((await db.query('select operation from library_sync_pending')).rows[0].operation,'delete');
 await db.exec(`set request.jwt.claim.sub='${other}';`);
 assert.equal((await db.query('select * from library_sync_pending')).rows.length,0);
 await assert.rejects(db.exec(`insert into library_sync_pending(user_id,provider,account_id,media_type,mal_id,operation) values ('${other}','anilist',1,'anime',2,'delete');`));
 await db.exec(`reset role;set request.jwt.claim.role='service_role';update user_media_progress set current_episode=12;`);
 assert.equal((await db.query('select operation from library_sync_pending')).rows[0].operation,'delete');
 } finally {await db.close();}
});
